"""Generate the static paper page and shared metadata from paper.json (stdlib only)."""
from html import escape
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'site'


def tex(text):
    for letter, escaped in {'á': r"{\'a}", 'ö': r'{\"o}', 'ü': r'{\"u}'}.items():
        text = text.replace(letter, escaped)
    return text


def main():
    paper = json.loads((ROOT / 'pipeline/paper.json').read_text())
    title = paper['title']
    authors = [f"{a['given']} {a['family']}" for a in paper['authors']]
    author_links = [{'name': name, 'url': author['url']} for name, author in zip(authors, paper['authors'])]
    authors_html = ', '.join(f'<a href="{escape(a["url"], quote=True)}">{escape(a["name"])}</a>' for a in author_links)
    bib_authors = ' and '.join(tex(f"{a['family']}, {a['given']}") for a in paper['authors'])
    bib_title = title.replace('LeanLean', '{LeanLean}').replace(' Lean ', ' {Lean} ')
    citation = f"""@misc{{leanlean{paper['year']},
  title  = {{{bib_title}}},
  author = {{{bib_authors}}},
  year   = {{{paper['year']}}},
  note   = {{Preprint}},
  url    = {{{paper['citation_url']}}}
}}"""
    meta = [('citation_title', title), *[('citation_author', a) for a in authors],
            ('citation_publication_date', str(paper['year'])),
            ('citation_pdf_url', paper['site_url'] + 'paper.pdf')]
    tags = '\n'.join(f'<meta name="{name}" content="{escape(value, quote=True)}">' for name, value in meta)
    html = f'''<!doctype html>
<!-- Generated by pipeline/build_paper.py; edit pipeline/paper.json. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<link rel="canonical" href="{escape(paper['site_url'], quote=True)}paper.html">
{tags}
<style>
  :root {{ color-scheme: light; background: #fbfcfc; color: #172b2a; }}
  body {{ max-width: 48rem; margin: auto; padding: 2rem 1.25rem; font: 1.05rem/1.65 system-ui, sans-serif; }}
  h1, h2 {{ font-family: Georgia, serif; line-height: 1.2; font-weight: 500; }}
  h1 {{ font-size: clamp(1.8rem, 5vw, 2.5rem); margin-bottom: 1rem; }}
  h2 {{ font-size: 1.5rem; margin-top: 2rem; }}
  a {{ color: #14685b; text-underline-offset: .2em; }}
  .authors {{ margin-bottom: .25rem; }}
  .authors a {{ color: inherit; text-decoration: none; }}
  .authors a:hover, .authors a:focus-visible {{ text-decoration: underline; }}
  .year {{ margin-top: 0; color: #536866; }}
  pre {{ padding: 1rem; border: 1px solid #dce5e3; border-radius: .5rem; background: #f0f5f3; white-space: pre-wrap; overflow-wrap: anywhere; font-size: .8rem; }}
</style>
</head>
<body>
<main>
<h1>{escape(title)}</h1>
<p class="authors">{authors_html}</p>
<p class="year">{paper['year']} · Preprint</p>
<p><a href="paper.pdf">Read the PDF</a> · <a href="./">Explore the benchmark</a></p>
<section aria-labelledby="abstract">
<h2 id="abstract">Abstract</h2>
<p>{escape(paper['abstract'])}</p>
</section>
<section aria-labelledby="citation">
<h2 id="citation">Citation</h2>
<pre><code>{escape(citation)}</code></pre>
</section>
</main>
</body>
</html>
'''
    (SITE / 'paper.html').write_text(html, encoding='utf-8')

    # Embed only the four small values used by the benchmark, with no runtime fetch.
    values = {'PAPER_TITLE': title, 'AUTHORS': author_links, 'PAPER_URL': 'paper.html', 'CITATION': citation}
    block = '// BEGIN GENERATED PAPER METADATA\n// Generated by pipeline/build_paper.py; edit pipeline/paper.json.\n'
    block += '\n'.join(f'export const {key} = {json.dumps(value, ensure_ascii=False)};' for key, value in values.items())
    block += '\n// END GENERATED PAPER METADATA'
    path = SITE / 'assets/js/util.js'
    source = path.read_text()
    start = source.index('// BEGIN GENERATED PAPER METADATA')
    end = source.index('// END GENERATED PAPER METADATA') + len('// END GENERATED PAPER METADATA')
    path.write_text(source[:start] + block + source[end:], encoding='utf-8')

    # Keep the existing homepage's author and title tags in sync too.
    path = SITE / 'index.html'
    source = path.read_text()
    for attr, key, value in [('name', 'author', ', '.join(authors)),
                             ('property', 'og:title', title), ('name', 'twitter:title', title)]:
        source = re.sub(rf'<meta {attr}="{key}" content="[^"]*">',
                        lambda _: f'<meta {attr}="{key}" content="{escape(value, quote=True)}">', source)
    path.write_text(source, encoding='utf-8')
    print('Generated paper.html and shared paper metadata')


if __name__ == '__main__':
    main()
